#!/usr/bin/env python3
"""Fixed TRAIN readiness only; gradients measured without any optimizer update."""
import argparse
import json
import time
from pathlib import Path
import numpy as np
import torch
import feature_smoke as F
import manifest as M
from src.m28.core import M28Core
from src.m28.candidates import generate,Budget
from src.m28.labels import build_targets,CDS_COLUMNS
from src.m28.training import one_hot
from src.m28.prefix_search import generate_prefix
from src.m28.prefix_value import PrefixValue
from src.m28.prefix_training import FirstCutObserver,prefix_losses

def train_records(path):
    # Existing mixed catalogs/indexes are generated by json.dumps with this field.
    # Filter the split tag before parsing any non-TRAIN reference values.
    with path.open() as f:
        for line in f:
            if '"split": "train"' not in line: continue
            row=json.loads(line)
            if row['split']!='train': raise ValueError('TRAIN metadata filter mismatch')
            yield row

def main(sample_path,out):
    sample=json.loads(sample_path.read_text());draws=sample['draws']
    if len(draws)!=12 or sample['optimizer_step'] or sample['DEV_forward']:
        raise ValueError('Frozen preparation sample mismatch')
    ids={d['window_id'] for d in draws}
    if len(ids)!=12 or len({(d['species'],*d['stratum']) for d in draws})!=12:
        raise ValueError('Expected 12 TRAIN strata')
    if out.exists(): raise FileExistsError(out)
    out.mkdir(parents=True);began=time.perf_counter()
    index={r['window_id']:r for r in train_records(M.C.ROOT/'outputs/M28-PILOT-R5/features/index.jsonl') if r['window_id'] in ids}
    windows={};catalogs={}
    label_root=M.C.ROOT/'outputs/M28-LABEL-POLICY-R4'
    for species in ('arabidopsis_thaliana','oryza_sativa'):
        windows.update({w['id']:w for w in train_records(label_root/species/'windows_train.jsonl') if w['id'] in ids})
        needed={ident for w in windows.values() if w['species']==species for ident in w['overlapping_transcript_ids']}
        catalogs[species]={t['id']:t for t in train_records(label_root/species/'transcripts.jsonl') if t['id'] in needed}
        if set(catalogs[species])!=needed: raise ValueError('TRAIN target identity mismatch')
    if set(index)!=ids or set(windows)!=ids: raise ValueError('TRAIN window/feature identity mismatch')
    for d in draws:
        w=windows[d['window_id']]
        if (w['species'],w['seqid'],w['strand'])!=(d['species'],*d['stratum']):
            raise ValueError('TRAIN stratum mismatch')
        if any(t['seqid']!=w['seqid'] or t['strand']!=w['strand']
               for t in (catalogs[w['species']][i] for i in w['overlapping_transcript_ids'])):
            raise ValueError('TRAIN transcript/window mismatch')
    checkpoint=M.C.ROOT/'outputs/M28-PILOT-R5/B1/step_004608.pt'
    state=torch.load(checkpoint,map_location='cpu',weights_only=True)
    if state['arm']!='B1' or state['step']!=4608 or state['revision']!=F.REVISION:
        raise ValueError('Frozen base identity mismatch')
    torch.set_num_threads(2)
    base=M28Core('B1',2048,128)
    base.load_state_dict(state['model'],strict=True);del state
    base.eval().requires_grad_(False).to('cuda')
    torch.manual_seed(0)
    model=PrefixValue(128).to('cuda').train()
    torch.cuda.reset_peak_memory_stats();records=[]
    with (out/'windows.jsonl').open('x') as log:
        for d in draws:
            step_began=time.perf_counter();timing={}
            w=windows[d['window_id']];n=w['valid_bases']
            cached=torch.load(M.C.ROOT/index[d['window_id']]['artifact'],map_location='cpu',weights_only=True)
            if (cached['revision']!=F.REVISION or len(cached['sequence'])!=n or
                tuple(cached['features'].shape)!=(4096,2048) or
                any(cached['window'][k]!=w[k] for k in ('id','species','seqid','strand','start','end','valid_bases'))):
                raise ValueError('TRAIN feature/geometry mismatch')
            sequence=cached['sequence']
            features=cached['features'].float()[None].to('cuda');dna=one_hot(sequence,w['width'])[None].to('cuda')
            torch.cuda.synchronize();timing['load_seconds']=time.perf_counter()-step_began
            t=time.perf_counter()
            # no_grad, not inference_mode: the frozen outputs feed trainable head layers.
            with torch.no_grad():
                outputs=base(features,dna,[n]);h=outputs['features'][0,:n]
                p=outputs['segmentation_logits'][0,:n].softmax(-1)
                ep=outputs['endpoint_logits'][0,:n].cpu().numpy()
                cp=p[:,list(CDS_COLUMNS)].sum(-1).cpu().numpy()
            torch.cuda.synchronize();timing['frozen_forward_seconds']=time.perf_counter()-t
            targets=build_targets(w,catalogs[w['species']],sequence)
            observer=FirstCutObserver(targets['positive_chains'])
            links=lambda pairs:base.chain.link_logits(h,pairs).cpu().numpy()
            t=time.perf_counter()
            with torch.no_grad():
                free=generate_prefix(sequence,ep,cp,links,Budget(),observer=observer)
                original=generate(sequence,ep,cp,links,Budget())
            if free!=original: raise ValueError('Additive training control diverged from original')
            torch.cuda.synchronize();timing['control_search_and_replay_seconds']=time.perf_counter()-t
            t=time.perf_counter()
            with torch.no_grad():
                early_scorer=model.for_window(h)
                early=generate_prefix(sequence,ep,cp,links,Budget(),rank_states_fn=early_scorer.priorities)
            torch.cuda.synchronize();timing['untrained_early_search_seconds']=time.perf_counter()-t
            del early_scorer
            t=time.perf_counter()
            model.zero_grad(set_to_none=True)
            result=prefix_losses(model,h,free,observer,targets,d['importance_weight_uniform_within_stratum'])
            if not torch.isfinite(result['total']): raise ValueError('Nonfinite readiness loss')
            result['total'].backward()
            gradnorm=torch.nn.utils.clip_grad_norm_(model.parameters(),1.,error_if_nonfinite=True)
            if any(p.grad is not None for p in base.parameters()): raise ValueError('Frozen base received gradient')
            torch.cuda.synchronize();timing['loss_backward_seconds']=time.perf_counter()-t
            record={'window_id':w['id'],'species':w['species'],'stratum':d['stratum'],
                    'importance_weight':d['importance_weight_uniform_within_stratum'],
                    'free_control_candidates':len(free['chains']),'untrained_early_candidates':len(early['chains']),
                    'control_counts':free['counts'],'untrained_early_counts':early['counts'],
                    'final_label_counts':{str(y):result['final_labels'].count(y) for y in (-1,0,1)},
                    'reference_injected':result['origins'].count('reference_injected'),
                    'first_cut_events':result['first_cut_events'],'known_rank_pairs':result['known_rank_pairs'],
                    'unknown_competitors':result['unknown_competitors'],
                    'final_loss':float(result['final'].detach()),'rank_loss':float(result['rank'].detach()),
                    'weighted_total':float(result['total'].detach()),'gradient_norm_before_clip':float(gradnorm),
                    'base_parameters_with_gradient':0,'optimizer_steps':0,'seconds':timing,
                    'window_wall_seconds':time.perf_counter()-step_began}
            log.write(json.dumps(record,allow_nan=False)+'\n');log.flush();records.append(record)
            print(json.dumps(record,allow_nan=False),flush=True)
            del cached,features,dna,outputs,h,p,targets,observer,free,original,early,result
    if len(records)!=12: raise ValueError('Incomplete fixed preparation')
    report={'experiment':'M28-B2-PREPARATION','completed':True,'windows':12,'optimizer_steps':0,
            'fitting':False,'head_seed':0,'trainable_parameters':sum(p.numel() for p in model.parameters()),
            'base_checkpoint':str(checkpoint.relative_to(M.C.ROOT)),'base_trainable_parameters':0,
            'feature_revision':F.REVISION,'DEV_forward_used':False,'test_setaria_used':False,
            'known_rank_pairs':sum(r['known_rank_pairs'] for r in records),
            'first_cut_events':sum(r['first_cut_events'] for r in records),
            'unknown_competitors':sum(r['unknown_competitors'] for r in records),
            'record_count':len(records),'sample_manifest':str(sample_path.relative_to(M.C.ROOT)),
            'wall_seconds':time.perf_counter()-began,
            'seconds_total_by_stage':{k:sum(r['seconds'][k] for r in records) for k in records[0]['seconds']},
            'peak_gpu_allocated_bytes':torch.cuda.max_memory_allocated(),
            'peak_gpu_reserved_bytes':torch.cuda.max_memory_reserved(),
            'new_method_performance_claim':False,'head_updated':False}
    with (out/'summary.json').open('x') as f: json.dump(report,f,indent=2,allow_nan=False);f.write('\n')
    if sum(p.stat().st_size for p in out.iterdir() if p.is_file())>32*1024**2: raise RuntimeError('Preparation output cap')
    print(json.dumps(report,indent=2),flush=True)

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--sample',type=Path,required=True);p.add_argument('--output-dir',type=Path,required=True)
    a=p.parse_args();main(a.sample.resolve(),a.output_dir.resolve())
